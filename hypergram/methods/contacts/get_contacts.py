from __future__ import annotations as _annotations

import logging

import hypergram
from hypergram import raw
from hypergram import types

log = logging.getLogger(__name__)


class GetContacts:
    async def get_contacts(self: hypergram.Client) -> list[types.User]:
        """Get contacts from your Telegram address book.

        .. include:: /_includes/usable-by/users.rst

        Returns:
            List of :obj:`~hypergram.types.User`: On success, a list of users is returned.

        Example:
            .. code-block:: python

                contacts = await app.get_contacts()
                print(contacts)
        """
        contacts = await self.invoke(raw.functions.contacts.GetContacts(hash=0))
        return types.List([await types.User._parse(self, user) for user in contacts.users])
